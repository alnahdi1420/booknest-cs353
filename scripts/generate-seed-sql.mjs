// Generates supabase/seed.sql from lib/demo/books.json so Demo Mode and Supabase
// use exactly the same catalog. Run: npm run seed:sql
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const books = JSON.parse(readFileSync(join(root, "lib/demo/books.json"), "utf8"));

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = books.map(
  (b) =>
    `  (${q(b.id)}, ${q(b.title)}, ${q(b.author)}, ${q(b.category)}, ${q(b.summary)}, ${b.price.toFixed(2)}, ${b.stock}, ${b.pages}, ${b.year}, ${b.featured}, ${q(b.coverFrom)}, ${q(b.coverTo)})`,
);

const sql = `-- BookNest sample catalog (${books.length} books). Generated by scripts/generate-seed-sql.mjs - do not edit by hand.
-- Safe to run more than once: existing books are updated (stock is reset to the sample value).
-- Run AFTER the migration: Supabase Dashboard -> SQL Editor -> paste -> Run.

insert into public.books (id, title, author, category, summary, price, stock, pages, year, featured, cover_from, cover_to)
values
${rows.join(",\n")}
on conflict (id) do update set
  title = excluded.title,
  author = excluded.author,
  category = excluded.category,
  summary = excluded.summary,
  price = excluded.price,
  stock = excluded.stock,
  pages = excluded.pages,
  year = excluded.year,
  featured = excluded.featured,
  cover_from = excluded.cover_from,
  cover_to = excluded.cover_to,
  updated_at = now();
`;

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`Wrote supabase/seed.sql with ${books.length} books.`);
